const _hex = h => [1, 3, 5].map(i => parseInt(h.slice(i, i + 2), 16));
const _rgb = a => '#' + a.map(v => Math.max(0, Math.min(255, Math.round(v))).toString(16).padStart(2, '0')).join('');
const shade = (h, f) => _rgb(_hex(h).map(v => v * f));
const lighten = (h, f) => _rgb(_hex(h).map(v => v + (255 - v) * f));
const _cache = {};
function spriteCanvas(shape, c1, c2) {
  const key = shape + c1 + (c2 || ''); if (_cache[key]) return _cache[key];
  const c = document.createElement('canvas'); c.width = c.height = 8;
  const g = c.getContext('2d'), pal = { 1: c1, 2: shade(c1, .5), 3: c2 || lighten(c1, .45), 4: '#f8fafc' };
  SHAPES[shape].forEach((row, y) => { for (let x = 0; x < 8; x++) { const ch = row[x]; if (ch !== '.') { g.fillStyle = pal[ch]; g.fillRect(x, y, 1, 1) } } });
  return _cache[key] = c;
}
